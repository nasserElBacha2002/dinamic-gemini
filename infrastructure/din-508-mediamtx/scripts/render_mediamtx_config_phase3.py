#!/usr/bin/env python3
"""Render mediamtx.yml for Phase 3 integration (authHTTP → FastAPI)."""

from __future__ import annotations

import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def _append_mtx_key(url: str, secret: str) -> str:
    if not secret:
        return url
    sep = "&" if "?" in url else "?"
    return f"{url}{sep}mtx_key={secret}"


def main() -> int:
    auth_url = (os.getenv("MEDIAMTX_AUTH_HTTP_URL") or "").strip()
    mtx_key = (os.getenv("MEDIAMTX_HTTP_AUTH_SECRET") or "").strip()
    if not auth_url:
        print(
            "Set MEDIAMTX_AUTH_HTTP_URL (e.g. http://host.docker.internal:8000/api/internal/mediamtx/auth)",
            file=sys.stderr,
        )
        return 2
    if not mtx_key:
        print("Set MEDIAMTX_HTTP_AUTH_SECRET for authHTTP callback (mtx_key query param)", file=sys.stderr)
        return 2
    auth_http_address = _append_mtx_key(auth_url, mtx_key)
    body = f"""# Generated by render_mediamtx_config_phase3.py — do not commit.

logLevel: info
logDestinations: [stdout]

authMethod: http
authHTTPAddress: {auth_http_address}
authHTTPExclude:
  - action: api
    ip: 127.0.0.1

api: yes
apiAddress: :9997

metrics: no
pprof: no
playback: no

rtsp: no
webrtc: no
srt: no

rtmp: yes
rtmpAddress: :1935
rtmpEncryption: "no"

hls: yes
hlsAddress: :8888
hlsEncryption: no
hlsAllowOrigin: '*'
hlsVariant: fmp4
hlsSegmentCount: 7
hlsSegmentDuration: 1s
hlsMuxerCloseAfter: 60s

pathDefaults:
  record: no
  source: publisher
  overridePublisher: no

paths:
  all_others:
    source: publisher
    record: no
"""
    out = ROOT / "generated" / "mediamtx.yml"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(body, encoding="utf-8")
    print(out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())