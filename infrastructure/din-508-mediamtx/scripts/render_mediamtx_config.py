#!/usr/bin/env python3
"""Render mediamtx.yml from template + local .env (no secrets in git)."""

from __future__ import annotations

import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
from channel_id import mediamtx_path, normalize_inventory_id  # noqa: E402

RESERVED_USERS = frozenset({"any", ""})


def load_env(env_path: Path) -> dict[str, str]:
    if not env_path.is_file():
        raise FileNotFoundError(f"Missing {env_path}; copy .env.example to .env")
    out: dict[str, str] = {}
    for line in env_path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if "=" not in line:
            continue
        key, _, value = line.partition("=")
        out[key.strip()] = value.strip()
    return out


def yaml_escape(value: str) -> str:
    if any(c in value for c in ":\"'#"):
        return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'
    return value


def validate_credentials(env: dict[str, str]) -> None:
    users = [
        env["POC_PUB_A_USER"],
        env["POC_VIEW_A_USER"],
        env["POC_PUB_B_USER"],
        env["POC_VIEW_B_USER"],
    ]
    if len(users) != len(set(users)):
        raise ValueError("POC publish/view usernames must be unique across channels")
    for u in users:
        if u in RESERVED_USERS:
            raise ValueError(f"POC username {u!r} is reserved and would break isolation")
        if not u.strip():
            raise ValueError("POC usernames must be non-empty")


def main() -> int:
    env = load_env(ROOT / ".env")
    required = [
        "POC_INVENTORY_A",
        "POC_INVENTORY_B",
        "POC_AISLE_CODE_A",
        "POC_AISLE_CODE_B",
        "POC_PUB_A_USER",
        "POC_PUB_A_PASS",
        "POC_VIEW_A_USER",
        "POC_VIEW_A_PASS",
        "POC_PUB_B_USER",
        "POC_PUB_B_PASS",
        "POC_VIEW_B_USER",
        "POC_VIEW_B_PASS",
    ]
    missing = [k for k in required if not env.get(k) or "replace-with-local" in env.get(k, "")]
    if missing:
        print(
            "Set real POC_* secrets in infrastructure/din-508-mediamtx/.env "
            f"(missing or placeholder: {', '.join(missing)})",
            file=sys.stderr,
        )
        return 2

    validate_credentials(env)
    inv_a = normalize_inventory_id(env["POC_INVENTORY_A"])
    inv_b = normalize_inventory_id(env["POC_INVENTORY_B"])
    path_a = mediamtx_path(inv_a, env["POC_AISLE_CODE_A"])
    path_b = mediamtx_path(inv_b, env["POC_AISLE_CODE_B"])

    def user_block(user: str, password: str, actions: list[tuple[str, str]]) -> str:
        lines = [f"  - user: {yaml_escape(user)}", f"    pass: {yaml_escape(password)}", "    ips: []", "    permissions:"]
        for action, path in actions:
            lines.append(f"      - action: {action}")
            lines.append(f"        path: {yaml_escape(path)}")
        return "\n".join(lines)

    auth_users = "\n".join(
        [
            user_block(env["POC_PUB_A_USER"], env["POC_PUB_A_PASS"], [("publish", path_a)]),
            user_block(
                env["POC_VIEW_A_USER"],
                env["POC_VIEW_A_PASS"],
                [("read", path_a), ("playback", path_a)],
            ),
            user_block(env["POC_PUB_B_USER"], env["POC_PUB_B_PASS"], [("publish", path_b)]),
            user_block(
                env["POC_VIEW_B_USER"],
                env["POC_VIEW_B_PASS"],
                [("read", path_b), ("playback", path_b)],
            ),
            "  - user: any",
            "    pass:",
            "    ips: ['127.0.0.1', '::1']",
            "    permissions:",
            "      - action: api",
        ]
    )

    body = f"""# Generated by scripts/render_mediamtx_config.py — do not edit; do not commit.

logLevel: info
logDestinations: [stdout]

authMethod: internal
authInternalUsers:
{auth_users}

api: yes
apiAddress: 127.0.0.1:9997

metrics: no
pprof: no
playback: no

rtsp: no
webrtc: no
srt: no

rtmp: yes
rtmpAddress: :1935
rtmpEncryption: "no"

hls: yes
hlsAddress: :8888
hlsEncryption: no
hlsAllowOrigin: '*'
hlsVariant: mpegts
hlsSegmentCount: 7
hlsSegmentDuration: 1s
hlsMuxerCloseAfter: 60s

pathDefaults:
  record: no
  source: publisher
  overridePublisher: no

paths:
  all_others:
    source: publisher
    record: no
"""

    out_dir = ROOT / "generated"
    out_dir.mkdir(parents=True, exist_ok=True)
    out_path = out_dir / "mediamtx.yml"
    out_path.write_text(body, encoding="utf-8")
    meta = out_dir / "channel-paths.txt"
    meta.write_text(f"path_a={path_a}\npath_b={path_b}\n", encoding="utf-8")
    print(out_path)
    print(meta)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())